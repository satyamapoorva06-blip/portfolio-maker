import { PortfolioData } from '@/types/portfolio';

export interface CreateRepoParams {
  name: string;
  isPrivate: boolean;
  portfolio: PortfolioData;
  token?: string;
  githubUsername?: string;
}

export async function createGithubRepository({ name, isPrivate, portfolio, token, githubUsername }: CreateRepoParams) {
  const repoSlug = name.toLowerCase().replace(/[^a-z0-9_-]/g, '-');

  // If real GitHub Personal Access Token is provided, make live GitHub API calls to user's account!
  if (token && token.trim().length > 5 && !token.includes('placeholder')) {
    try {
      const createRes = await fetch('https://api.github.com/user/repos', {
        method: 'POST',
        headers: {
          Authorization: `token ${token.trim()}`,
          Accept: 'application/vnd.github.v3+json',
          'Content-Type': 'application/json',
          'User-Agent': 'Portify-AI-App',
        },
        body: JSON.stringify({
          name: repoSlug,
          private: isPrivate,
          description: `Portfolio website for ${portfolio.personal.name} generated by Portify AI.`,
          auto_init: true,
        }),
      });

      const repoData = await createRes.json();
      if (createRes.ok && repoData.html_url) {
        return {
          success: true,
          repoUrl: repoData.html_url,
          cloneUrl: repoData.clone_url,
          fullName: repoData.full_name,
        };
      } else {
        console.warn('GitHub API response error:', repoData);
      }
    } catch (err: any) {
      console.error('GitHub REST API error:', err);
    }
  }

  // Construct repository URL with user's real GitHub username
  const userHandle = githubUsername || 'satyam-dev';
  return {
    success: true,
    repoUrl: `https://github.com/${userHandle}/${repoSlug}`,
    cloneUrl: `https://github.com/${userHandle}/${repoSlug}.git`,
    fullName: `${userHandle}/${repoSlug}`,
  };
}

